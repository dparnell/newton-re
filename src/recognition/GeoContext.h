/*
	File:		recognition/GeoContext.h

	Contains:	What the geometry between two letters costs.

				This is the part of the lexical search that looks at
				how two pieces of writing *sit against each other*
				rather than at what they look like on their own.  It is
				what tells `rn` from `m`: the classifier sees much the
				same ink either way, and only the two boxes' sizes and
				places say which reading the writer meant.

				The engine keeps a nominal drawing of every character -
				sixteen numbers apiece in `rosCharParams`, all as
				fractions of the cap height: where its bottom sits above
				the baseline, how tall it is, how wide, how much room it
				wants before and after it, and how big its smallest
				stroke ought to be when it is written in one stroke and
				when it is written in more.  Given two character codes
				and the two segments they would be read from, it lays
				the two nominal boxes side by side, lays the two
				observed boxes beside each other likewise, brings both
				pairs to the same size and place, and measures the nine
				ways they differ.

				Those nine residuals are then put through a symmetric
				nine-by-nine matrix (`kGeoWeights`) as a **quadratic
				form** - `sum over i of v[i] times sum over j of
				M[i][j] v[j]` - which is a Mahalanobis distance: the
				residuals are not simply added up, they are weighed
				against each other, so that (say) both boxes being a
				little too tall costs much less than one being too tall
				and the other too short.  The answer is scaled by
				`RosCommonInfo::fGeoWeight` and handed back as a score
				in the engine's own units, which are negative natural
				logarithms times five hundred.

				Because `SearchDoVStepFromNode` asks the same question
				over and over for the same pair of segments, the answers
				are cached: a hundred (first character, second
				character) pairs, thrown away whenever the pair of
				segments changes, which the search also does by hand
				through `GeoContextClearCache`.

	Reconstructed from the MP2x00 US ROM (0x000d9ad4-0x000daee8); each
	function cites its origin.
*/

