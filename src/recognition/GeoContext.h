// What it costs to read `now` out of `nowSeg` with `before` out of
// `beforeSeg` in front of it.  Either character may be nought, meaning
// the start or the end of the word, and `acrossWords` says the two are
// in different words.  A character of 0x1f is the engine's own
// stand-in and costs four times as much.
