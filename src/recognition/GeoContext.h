struct RosSegment;

// The sixteen numbers `rosCharParams` holds for each character code,
// all as fractions of the cap height.  The first seven are the nominal
// drawing of the character and the next seven are what each measurement
// of it is worth; the last two are not read here.
const long	kGeoBottom			= 0;	// its bottom, above the baseline
const long	kGeoHeight			= 1;	// ... and how tall it is
const long	kGeoWidth			= 2;	// how wide
const long	kGeoGapBefore		= 3;	// the room it wants before it
const long	kGeoGapAfter		= 4;	// ... and after it
const long	kGeoStrokeOne		= 5;	// its smallest stroke, written in one
const long	kGeoStrokeMany		= 6;	// ... and written in more than one
const long	kGeoWeightBottom	= 7;
const long	kGeoWeightTop		= 8;
const long	kGeoWeightWidth		= 9;
const long	kGeoWeightGapBefore	= 10;
const long	kGeoWeightGapAfter	= 11;
const long	kGeoWeightStrokeOne	= 12;
const long	kGeoWeightStrokeMany = 13;

// The nine things measured, in the order the weight matrix wants them.
const long	kGeoBottom1		= 0;
const long	kGeoBottom2		= 1;
const long	kGeoTop1		= 2;
const long	kGeoTop2		= 3;
const long	kGeoWidth1		= 4;
const long	kGeoWidth2		= 5;
const long	kGeoGap			= 6;	// between the two, when they are neighbours
const long	kGeoStroke1		= 7;
const long	kGeoStroke2		= 8;
const long	kGeoMeasurements = 9;

// The quadratic form the nine are weighed through: symmetric, so it is
// a covariance and this is a Mahalanobis distance.
// GeoTables.cpp, generated by analysis/romtable.py
extern const int	kGeoWeights[81];			// ROM 0x003714d0 (unnamed)

// One piece of writing as the geometry sees it.  `GeoContextAux1` fills
// two of these out of the two segments and brings them to a common size
// and place; the y values are turned over, so that up is positive as it
// is in the nominal drawing, and everything is divided by 64 first so
// that the sums below cannot overflow a 16.16 number.
struct GeoBox
{
	Fixed		fWidth;				// +0x00  right - left
	Fixed		fSmallestStroke;	// +0x04  the segment's own
	Fixed		fBottom;			// +0x08  -bounds.bottom
	Fixed		fTop;				// +0x0c  -bounds.top
	Fixed		fLeft;				// +0x10
	Fixed		fRight;				// +0x14
};

