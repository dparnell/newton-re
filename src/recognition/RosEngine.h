// The block of trained numbers the whole engine measures against.  The
// ROM's is 0x10c bytes and `CharInitialize` makes one by copying the
// template `rosCI` (`RosCITables.cpp`, generated by
// `analysis/rosci.py`) into a block of its own, because an area may
// replace `fLegalUse` with a set of its own.
//
// A field named `fFieldNNN` is one nothing reconstructed so far reads;
// the offsets in the comments are the ROM's.
struct RosCommonInfo
{
	// Four numbers per character code saying how likely it is to be
	// written in one, two, three or four strokes.  Nil in the US ROM,
	// and `fStrokeCountWeight` is nought to match, so nothing uses it.
	const Fixed*		fCharStrokeProbs;	// +0x00
	ULong				fField04[2];		// +0x04
	// eight numbers per character code, on eight scales of the
	// engine's own.  Table 1 is the nominal width a character takes,
	// which is what the cap height is worked out from.
	const Fixed* const*	fCharParams;		// +0x0c  rosCharParams
	ULong				fField10;			// +0x10
	// 256 bits each: which character codes there are, and which of
	// them the engine may answer at the moment.  `fLegalUse` starts as
	// the ROM's own `rosCharLegalUse` and is replaced by a set of the
	// area's when one is set, which is what `RSfRcl` checks before it
	// gives the block back.
	const ULong*		fLegalNet;			// +0x14  rosCharLegalNet
	const ULong*		fLegalUse;			// +0x18  rosCharLegalUse
	// the classifier's output nodes and the character codes they stand
	// for, each way round
	const UByte*		fCharOfNetNode;		// +0x1c  rosCharOfNetNode
	const UByte*		fCharToNetNode;		// +0x20  rosCharToNetNode
	// a character that is really two: the two it is made of, whose net
	// outputs are multiplied together to score it
	const UByte*		fCompoundPart1;		// +0x24  rosCharCompoundPart1
	const UByte*		fCompoundPart2;		// +0x28  rosCharCompoundPart2
	// the capitals hack: whether a character has a case, and the one
	// or two characters it may be read as instead
	const UByte*		fCapCaseFlags;		// +0x2c  rosCapHackCaseFlags
	const UByte*		fCapAltCase1;		// +0x30  rosCapHackAltCase1
	const UByte*		fCapAltCase2;		// +0x34  rosCapHackAltCase2
	// The four things `CharModifyProbs` leans the classifier's answer
	// with, and how much each is worth.  **Two of them are nought in
	// the shipped ROM**: the stroke-count penalty and the shape fit
	// are compiled in and switched off, leaving the capitals hack and
	// the height model.
	Fixed				fStrokeCountWeight;	// +0x38  (0: off)
	Fixed				fCapCaseWeight;		// +0x3c  a fifth
	Fixed				fHeightSpread;		// +0x40  0.26 - and the gate for it
	Fixed				fShapeWeight;		// +0x44  (0: off)
	ULong				fField48;			// +0x48
	// under this a stroke has no shape at all - and, because it is the
	// same number, the smallest cap height that will be believed
	Fixed				fMinStrokeSize;		// +0x4c
	ULong				fField50;			// +0x50
	// The narrowest a letter may be taken to be, four pixels, and the
	// fractions of the writing's height that a letter is wide (a half)
	// and that two strokes must come within to count as touching (a
	// tenth).  `SegmentChars` works the two widths out from them.
	Fixed				fMinCharWidth;		// +0x54
	ULong				fField58[2];		// +0x58
	Fixed				fCharWidthFraction;	// +0x60
	Fixed				fReachFraction;		// +0x64
	ULong				fField68[4];		// +0x68
	// How wide a piece of writing may get before it is cut in two
	// whatever else the strokes say: one and a half times as wide as
	// it is tall, or one and three quarters when there is a dot
	// somewhere in it - because the dot has already widened the box
	// without being a letter of its own.
	Fixed				fCutAspect;			// +0x78
	Fixed				fCutAspectWithDot;	// +0x7c
	// How much of the line two neighbouring strokes must share before
	// they are said to be part of one letter.  Seven tenths on its
	// own; else sixty-five hundredths if they *cross*, or 0.675 if
	// they are joined somewhere other than end to end.  And no cut
	// may go between two strokes that share more than a half.
	Fixed				fLinkOverlap;		// +0x80
	Fixed				fCrossOverlap;		// +0x84
	Fixed				fJoinOverlap;		// +0x88
	Fixed				fBreakOverlap;		// +0x8c
	// how near an end of a stroke counts as *at* the end: three
	// tenths of its points at either end.  Two strokes whose nearest
	// points are both well inside them cross; two whose nearest
	// points are both at an end merely meet.
	Fixed				fEndFraction;		// +0x90
	// ... and how near two strokes must come to be said to touch at
	// all: three pixels.
	Fixed				fLinkDistance;		// +0x94
	ULong				fField98[6];		// +0x98
	// What the classifier's score for a letter is worth against
	// everything else the search weighs: four fifths.
	Fixed				fNetScoreWeight;	// +0xb0
	// What a character of each case costs in each of the twelve
	// contexts `CapHackDetermineContext` answers.  This is the
	// capitals model: what having just written a capital, or two,
	// or a lower-case letter, says about what may follow.
	UShort				fCapCostUpper[12];	// +0xb4
	UShort				fCapCostLower[12];	// +0xcc
	UShort				fCapCostOther[12];	// +0xe4
	// What a stroke costs the search when the letter it is part of
	// was written loosely.  Two shorts: nothing when the segment's
	// strokes lie on each other well (above `fStrokeCostGate`, a
	// half), and up to 322 when they do not, interpolated by the
	// confidence scaled by `fStrokeCostScale`.
	// (one word, because that is how the generated table writes it:
	//  the minimum is the high half and the maximum the low)
	ULong				fStrokeCost;		// +0xfc
	Fixed				fStrokeCostGate;	// +0x100
	Fixed				fStrokeCostScale;	// +0x104
	// What a piece of writing the engine cut for itself, or one that
	// runs into the next, is worth: one, so nothing.
	Fixed				fFragmentWeight;	// +0x108
};

