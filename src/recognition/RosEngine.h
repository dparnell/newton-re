/*--------------------------------------------------------------------
	The grammars.
--------------------------------------------------------------------*/

// One *kind of word*: a lexicon out of `gROMDictionaryData`, a score of
// its own, and a score for every kind that may follow it.  A lower
// score is better and 0x7ffe means never; they are the arithmetic
// coder's, which is what `ArProbDecodeLu` turns into a probability.
//
// `BiGSliceNew` (0x0003dfb4) allocates one with its two arrays behind
// it, so the ROM's object is 0x30 bytes plus six per transition.
struct BiGSlice
{
	const char*		fName;			// +0x00
	// Which lexicon, by its place in `gROMDictionaryData` - until
	// `RosettaSetArea` runs, which replaces the index with the data
	// itself.  A grammar the engine builds for an area has slices
	// named `~user` and `~null1`..`~null5` whose dictionary is filled
	// in later, and `RosettaClassifySetup` writes the *locked data
	// pointer* into this same field when it does.
	// DEVIATION: pointer-sized on the host, because that is what it
	// ends up holding and a host pointer is twice the ROM's.
	ULong			fDictionary;	// +0x04
	short			fScore;			// +0x08  what a word of this kind costs
	short			fField0a;		// +0x0a
	short			fCharCost;		// +0x0c  ... and each character of one
	short			fField0e;		// +0x0e
	long			fField10;		// +0x10  (bits: 0x2f, 0x15, 0x10, 0x0f, 5, 4)
	// What a capital and a lower-case letter cost in this kind of word.
	// `SearchDoVStepFromNode` charges the first pair on top of
	// everything else when the reading is in one of the upper six
	// capitals contexts, and the second pair *instead of* the common
	// info's twelve-entry tables when this kind of word says it will
	// have the case being tried.
	short			fCapExtraUpper;	// +0x14
	short			fCapExtraLower;	// +0x16
	short			fCapCostUpper;	// +0x18
	short			fCapCostLower;	// +0x1a
	// How many kinds may follow this one, and how many there is room
	// for.  `BiGSliceNew` sets the second and leaves the first at
	// nought; in the ROM's own tables they are equal, because those
	// slices are full.
	long			fNextCount;		// +0x1c
	long			fNextCapacity;	// +0x20
	const BiGSlice* const*	fNext;	// +0x24
	const short*	fWeights;		// +0x28  what each of them costs
	// What kind of lexicon this is.  `BiGSliceNew` sets 0xff and the
	// ROM's tables keep it in 36 of their 46 slices; the nine named
	// `LexicalSymbols` carry 0, and `wordlike` carries 1.
	UByte			fField2c;		// +0x2c
};

// One grammar: the name a field asks for it by, and its kinds of word.
// `BiGrammarNew` (0x0003de8c) allocates one with the slice array behind
// it, so the ROM's object is 0x20 bytes plus four per slice; the eight
// built into the ROM point at an array of their own instead.
struct BiGrammar
{
	const char*		fName;			// +0x00
	long			fField04;		// +0x04
	long			fCount;			// +0x08
	long			fCapacity;		// +0x0c
	const BiGSlice* const*	fSlices;	// +0x10
	UByte			fField14;		// +0x14
	// How many readings of each kind of word the search may keep in
	// one column, indexed by the lexicon class a slice carries in
	// `fField2c`.  The General grammar allows two of class 0 and two
	// of class 1, and nothing of the rest.
	UByte			fClassLimits[10];	// +0x15 .. +0x1e
	UByte			fPad1f;
};

// The list of them, as `BiGrammarsLoad` answers it.
struct BiGrammars
{
	long				fCount;		// +0x00
	const BiGrammar* const*	fContexts;	// +0x04
};

