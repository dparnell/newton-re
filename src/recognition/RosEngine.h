/*--------------------------------------------------------------------
	The arithmetic coder's two ways round.

	A grammar's scores are **negative natural logarithms of
	probabilities, scaled by five hundred**: a kind of word with an even
	chance costs 347, one chance in 65536 costs 5545, and 0x7ffe means
	never.  These two tables are how the engine goes between the two
	without a logarithm, and they are why `BiGrammarModifyContext` can
	reweigh a grammar in fixed point.

	`ArProbDecodeLu` answers the probability for a score, indexed by the
	score divided by eight, so it covers scores up to 0x2000 (a chance
	of about one in 34 million); anything dearer is nought.

	The other two go the other way and are chosen by how likely the
	thing is: `ArProbEncodeLu2` is indexed by the probability itself and
	covers the first 1/64 of the range finely, `ArProbEncodeLu1` by the
	probability over 128 for everything above that.
--------------------------------------------------------------------*/

// (`ArProbTables.cpp`, generated by `analysis/romtable.py` - do not edit)
extern const short	ArProbEncodeLu1[512];				// ROM 0x0036340c ArProbEncodeLu1
extern const short	ArProbEncodeLu2[1024];				// ROM 0x0036380c ArProbEncodeLu2
extern const int	ArProbDecodeLu[1024];				// ROM 0x0036400c ArProbDecodeLu

// The most a score may be and still mean anything, and the score that
// means never.
const long	kArProbNever		= 0x7ffe;
const long	kArProbMaxScore		= 0x2000;

// The two halves of the arithmetic coder's table lookup: the
// probability a score stands for, and the score a probability costs.
Fixed	ArProbDecode(long score);
short	ArProbEncode(Fixed probability);

// One kind of word, with room for `capacity` kinds after it and every
// other thing about it left to the caller.  The seven doubles are the
// training interface showing through and are not read.
BiGSlice*	BiGSliceCreate(const char* name, ULong dictionary,
					double a, double b, double c, long flag,
					double d, double e, double f, double g,
					short capacity);					// ROM 0x0003e048 BiGSliceCreate
// A kind of word looked up in a grammar by its dictionary and name, and
// added if it is not there yet.  This is what makes a clone's
// transitions point at the clone's own slices rather than the
// original's.
BiGSlice*	BiGrammarAddSlice(BiGrammar* grammar, ULong dictionary,
					const char* name, short capacity);	// ROM 0x0003e45c (unnamed)

// A grammar copied, slices, transitions and all.
BiGrammar*	BiGrammarClone(const BiGrammar* grammar);	// ROM 0x0003e534 BiGrammarClone
// A grammar cloned and then **reweighed**: the `count` kinds of word
// named by `slices` share `weight` of the probability, the rest share
// what is left, and every score is brought down so that the likeliest
// kind costs nothing.  This is what turns the General grammar into the
// grammar for a particular field.
BiGrammar*	BiGrammarModifyContext(const BiGrammar* grammar, long count,
					const long* slices, Fixed weight);	// ROM 0x0003e0c0 BiGrammarModifyContext


