#!/usr/bin/env python3
"""The Newton's DES, for a desktop's side of the dock password exchange.

Purpose
    A Newton and a desktop prove they share a password by each encrypting
    the other's 64-bit challenge under the password's DES key.  The
    Newton's DES is not quite the standard's - each 32-bit half of the key
    is shifted left a bit before PC1 - and its password-to-key function
    is its own, so a desktop has to do exactly what the ROM does.  This is
    a transcription of the reconstruction's src/utility/DES.cpp (itself
    checked against the ROM's own code by ctest utility.DES); the
    permutation tables are the ROM's (src/utility/DESTables.cpp, generated
    by tools/newton-rom/analysis/romtable.py), copied here so a desktop
    needs no ROM image.  docs/curiosities.md says how it differs.

Usage
    from newtondes import char_to_key, encode_nonce, decode_nonce
    key = char_to_key("")                   # the password's key: two words
    reply = encode_nonce(key, (hi, lo))     # a challenge encrypted
    python tools/dock/newtondes.py          # prints the self-check vectors

Inputs / outputs
    Words are Python ints (32 bits); a block or key is a pair of them, the
    first the high half.
"""

import sys

M = 0xFFFFFFFF


def _ror(v, n):
    n &= 31
    return v if n == 0 else ((v >> n) | (v << (32 - n))) & M


def permute(table, hi, lo):
    """The bits the table names gathered into two words."""
    current = previous = 0
    i = 0
    while True:
        bit = table[i]
        i += 1
        while bit < 0x40:
            current = (current << 1) & M
            source = hi if bit >= 0x20 else lo
            if source & (1 << (bit & 0x1f)):
                current |= 1
            bit = table[i]
            i += 1
        current, previous = previous, current
        if bit != 0x40:
            break
    return current, previous


def ip(hi, lo):
    a, a_shifted = hi, (hi << 16) & M
    b, b_shifted = lo, (lo << 16) & M
    r0 = r1 = 0
    for _ in range(2):
        r0 = _ror(r0, 1)
        r1 = _ror(r1, 1)
        for _ in range(8):
            r1 = ((r1 << 1) & M) | (b_shifted >> 31)
            b_shifted = (b_shifted << 1) & M
            r1 = _ror(r1, 31)
            r1 = ((r1 << 1) & M) | (b >> 31)
            b = (b << 1) & M
            r1 = _ror(r1, 31)
            r1 = ((r1 << 1) & M) | (a_shifted >> 31)
            a_shifted = (a_shifted << 1) & M
            r1 = _ror(r1, 31)
            r1 = ((r1 << 1) & M) | (a >> 31)
            a = (a << 1) & M
            nxt = _ror(r1, 31)
            r1 = r0
            r0 = nxt
    return r0, r1


def frk(k0, k1, r):
    result = 0
    bits = ((r << 1) & M) + (r >> 31)
    for i in range(8):
        result |= DESSBoxes[i * 0x40 + ((bits ^ k1) & 0x3f)]
        result = _ror(result, 4)
        bits = _ror(bits, 4)
        k1 = ((k1 >> 6) + (k0 << 26)) & M
        k0 >>= 6
    return permute(DESPTbl, 0, result)[1]


def key_schedule(key):
    rounds = 0xc0810000
    c, d = permute(DESPC1Tbl, (key[0] << 1) & M, (key[1] << 1) & M)
    c = (c << 4) & M
    d = (d << 4) & M
    schedule = []
    while True:
        c = (((c >> 27) & 0x10) + c * 2) & M
        d = (((d >> 27) & 0x10) + d * 2) & M
        while True:
            schedule.extend(permute(DESPC2Tbl, c, d))
            rounds = (rounds << 1) & M
            if rounds == 0:
                return schedule
            if rounds > 0x7fffffff:
                break
            c = (((c >> 26) & 0x30) + c * 4) & M
            d = (((d >> 26) & 0x30) + d * 4) & M


def encode(schedule, block):
    left, right = ip(block[0], block[1])
    k = 0
    for _ in range(8):
        left ^= frk(schedule[k], schedule[k + 1], right)
        right ^= frk(schedule[k + 2], schedule[k + 3], left)
        k += 4
    return permute(DESIPInvTbl, right, left)


def decode(schedule, block):
    left, right = ip(block[0], block[1])
    k = 32
    for _ in range(8):
        left ^= frk(schedule[k - 2], schedule[k - 1], right)
        right ^= frk(schedule[k - 4], schedule[k - 3], left)
        k -= 4
    return permute(DESIPInvTbl, right, left)


def encode_nonce(key, block):
    return encode(key_schedule(key), block)


def decode_nonce(key, block):
    return decode(key_schedule(key), block)


def char_to_key(password):
    """A password's key, as the ROM's DESCharToKey makes it (ROM bug and
    all: the parity-corrected bytes are ORed into the encrypted block)."""
    chars = [ord(c) for c in password] + [0]
    current = (0x57406860, 0x626d7464)          # "W@h`bmtd"
    ended = False
    nxt = 0
    while True:
        schedule = key_schedule(current)
        data = []
        for _ in range(4):
            if ended:
                data += [0, 0]
            else:
                c = chars[nxt] if nxt < len(chars) else 0
                nxt += 1
                data += [c >> 8, c & 0xff]
                if c == 0:
                    ended = True
        block = (int.from_bytes(bytes(data[:4]), "big"), int.from_bytes(bytes(data[4:]), "big"))
        block = encode(schedule, block)
        raw = block[0].to_bytes(4, "big") + block[1].to_bytes(4, "big")
        fixed = bytes(b ^ 1 if bin(b).count("1") % 2 == 0 else b for b in raw)
        current = (block[0] | int.from_bytes(fixed[:4], "big"), block[1] | int.from_bytes(fixed[4:], "big"))
        if ended:
            return current


